#!/bin/bash

PICOMUON_BASE_PATH=${PICOMUON_BASE_PATH:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)}
PICOMUON_FILE_OWNER=${PICOMUON_FILE_OWNER:-$(stat -c %U "$PICOMUON_BASE_PATH")}
PICOMUON_FILE_GROUP=${PICOMUON_FILE_GROUP:-$(id -gn "$PICOMUON_FILE_OWNER")}
FILE_OWNER=$PICOMUON_FILE_OWNER
export PICOMUON_BASE_PATH PICOMUON_FILE_OWNER PICOMUON_FILE_GROUP FILE_OWNER
export TERM=dumb
